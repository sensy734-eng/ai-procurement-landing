def build():
    docs = []
    for i, (name, paragraphs) in enumerate(DOCUMENTS):
        docs.append(dict(id=1001+i, name=name, version="2.0", demo=True,
                         chunks=[dict(id=10001+i*100+j, section=f"第{j+1}条", text=p)
                                 for j, p in enumerate(paragraphs)]))
    corpus = dict(version="demo-kb-v1", documents=docs)
    cases = []
    for i, (doc, chunk, category, *questions) in enumerate(FAMILIES):
        for variant, question in enumerate(questions):
            cases.append(dict(id=f"R{i+1:02}-{variant+1}", family=f"F{i+1:02}",
                              split="dev" if i < 15 else "holdout", category=category, question=question,
                              relevant_chunk_ids=[] if doc < 0 else [10001+doc*100+chunk]))
    return corpus, dict(version="retrieval-v1-frozen", cases=cases)

def main():
    folder = ROOT / "docs" / "evaluation"
    folder.mkdir(parents=True, exist_ok=True)
    corpus, dataset = build()
    for name, value in [("corpus.json", corpus), ("retrieval-v1.json", dataset)]:
        path = folder / name
        text = json.dumps(value, ensure_ascii=False, indent=2) + "\n"
        if path.exists() and path.read_text(encoding="utf-8") != text:
            raise SystemExit(f"Refusing to overwrite frozen artifact: {path}")
        path.write_text(text, encoding="utf-8", newline="\n")
    manifest = {p.name: hashlib.sha256(p.read_bytes()).hexdigest()
                for p in [folder/"corpus.json", folder/"retrieval-v1.json"]}
    (folder/"frozen-sha256.json").write_text(json.dumps(manifest, indent=2)+"\n", encoding="utf-8")
    def sql(value): return "'"+str(value).replace("'", "''")+"'"
    lines = ["-- Fictional demo corpus; reserved IDs 1001..1009 and 10001..10708.", "SET NAMES utf8mb4;"]
    for doc in corpus["documents"]:
        lines.append("INSERT INTO kb_document (id,doc_name,doc_type,version,status,parse_status,chunk_count,remark) VALUES "
                     f"({doc['id']},{sql(doc['name'])},1,'2.0',1,3,8,'虚构演示文本') ON DUPLICATE KEY UPDATE id=id;")
        for index, chunk in enumerate(doc["chunks"], 1):
            lines.append("INSERT INTO kb_chunk (id,doc_id,chunk_index,section_no,chunk_text,char_count) VALUES "
                         f"({chunk['id']},{doc['id']},{index},{sql(chunk['section'])},{sql(chunk['text'])},{len(chunk['text'])}) "
                         "ON DUPLICATE KEY UPDATE id=id;")
    lines.append("INSERT INTO kb_document (id,doc_name,doc_type,version,status,parse_status,chunk_count,remark) VALUES "
                 "(1009,'采购审批制度（演示）',1,'1.0',2,3,1,'停用旧版演示文本') ON DUPLICATE KEY UPDATE id=id;")
    lines.append("INSERT INTO kb_chunk (id,doc_id,chunk_index,section_no,chunk_text,char_count) VALUES "
                 "(10901,1009,1,'第二条','旧版演示：普通采购审批期限为5个工作日。此文档已停用。',31) ON DUPLICATE KEY UPDATE id=id;")
    (ROOT/"db"/"migrations"/"V20261109_02__demo_corpus.sql").write_text("\n".join(lines)+"\n", encoding="utf-8", newline="\n")

if __name__ == "__main__": main()
