-- ==============================================================
SET NAMES utf8mb4;
USE procurement_db;

-- --------------------------------------------------------------
-- 一、清检索测试记录（演示基线无测试记录）
-- --------------------------------------------------------------
DELETE FROM kb_retrieval_test;

-- --------------------------------------------------------------
-- 二、物理删冒烟文档及其切块与倒排索引
--    （演示文档 id 为 1/2，冒烟文档一律 id > 2 或 smk9 前缀）
-- --------------------------------------------------------------
DELETE FROM kb_sparse_index
WHERE chunk_id IN (SELECT id FROM kb_chunk WHERE doc_id > 2
                   OR doc_id IN (SELECT id FROM kb_document WHERE doc_name LIKE 'smk9%'));
DELETE FROM kb_chunk
WHERE doc_id > 2 OR doc_id IN (SELECT id FROM kb_document WHERE doc_name LIKE 'smk9%');
DELETE FROM kb_document WHERE id > 2 OR doc_name LIKE 'smk9%';

-- --------------------------------------------------------------
-- 三、兜底：清理逻辑删除残留行（is_deleted=1，正常流程不应存在）
-- --------------------------------------------------------------
DELETE FROM kb_sparse_index WHERE is_deleted = 1;
DELETE FROM kb_chunk WHERE is_deleted = 1;
DELETE FROM kb_document WHERE is_deleted = 1;

-- --------------------------------------------------------------
-- 四、清派生索引与向量（索引由程序生成，演示基线不带索引）
-- --------------------------------------------------------------
DELETE FROM kb_sparse_index;
UPDATE kb_chunk SET embedding = NULL, vector_model = NULL, vector_dim = 0;

