-- ============================================================
-- 文件：26_revert_ops_demo.sql
-- 作用：撤销轮次 11 的运营演示数据，把库回到「23_clean_smoke_round10」之后的基线
--
-- 为什么需要它：
--   24_init_ops_demo.sql 造的 7 张订单、2 张入库单、9 行库存与 2 条会签任务，
--   是为了让 P25/P26 两张页面一打开就有内容。但对**历史轮次**的冒烟来说，
--   这些数据是多出来的基线：轮次 7 的「预警只含 5 种物料」「对账 5 个键」
--   「归属分组 3 行」都按 19_clean 的干净基线写死，多出 4 种短缺物料就会失败。
--
--   前面各轮的 clean 脚本只删「自己那轮造的测试数据」（按 id 边界或单号前缀），
--   并不会去删演示数据，所以重跑回归链之前必须先跑本脚本。
--
-- 删除口径：只按本脚本认得的单号 / 批次号精确删除，不按 id 或前缀扫描，
--           因此不会波及 13_init_demo.sql 的基础单据与冒烟数据。
-- 幂等：数据不在时 DELETE 影响 0 行，可反复执行。
--
-- 执行时机：
--   重跑轮次 4~10 冒烟之前 → 本脚本 → 各轮 clean → 各轮冒烟
--   需要重新演示轮次 11 时 → 24_init_ops_demo.sql（脚本自带先删后插）
-- ============================================================

SET NAMES utf8mb4;
USE procurement_db;

-- ------------------------------------------------------------
-- 一、演示订单的交付流水与审批任务
-- ------------------------------------------------------------
DELETE FROM delivery_progress WHERE order_no IN (
  'CG-DD-20260415-0001', 'CG-DD-20260520-0001', 'CG-DD-20260618-0001',
  'CG-DD-20260722-0001', 'CG-DD-20260819-0001', 'CG-DD-20260910-0001',
  'CG-DD-20261027-0001');

DELETE FROM approval_task WHERE bill_no = 'CG-DD-20261027-0001';

-- ------------------------------------------------------------
-- 二、演示订单明细与主单（先子后父）
-- ------------------------------------------------------------
DELETE FROM purchase_order_item WHERE order_id IN (
  SELECT id FROM purchase_order WHERE order_no IN (
    'CG-DD-20260415-0001', 'CG-DD-20260520-0001', 'CG-DD-20260618-0001',
    'CG-DD-20260722-0001', 'CG-DD-20260819-0001', 'CG-DD-20260910-0001',
    'CG-DD-20261027-0001'));

DELETE FROM purchase_order WHERE order_no IN (
  'CG-DD-20260415-0001', 'CG-DD-20260520-0001', 'CG-DD-20260618-0001',
  'CG-DD-20260722-0001', 'CG-DD-20260819-0001', 'CG-DD-20260910-0001',
  'CG-DD-20261027-0001');

-- ------------------------------------------------------------
-- 三、演示入库单带来的库存与流水
--     注意顺序：先删流水再删余额（余额是流水的聚合结果，
--     反过来的话中途会短暂出现「余额有、流水无」的不一致窗口）
-- ------------------------------------------------------------
DELETE FROM stock_flow WHERE source_no IN ('CG-RK-20260401-0001', 'CG-RK-20260501-0001');
DELETE FROM stock_balance WHERE batch_no IN (
  'B20260401001', 'B20260401002', 'B20260401003', 'B20260401004', 'B20260401005',
  'B20260501001', 'B20260501002', 'B20260501003', 'B20260501004');

DELETE FROM inbound_item WHERE inbound_id IN (
  SELECT id FROM inbound_order WHERE inbound_no IN ('CG-RK-20260401-0001', 'CG-RK-20260501-0001'));
DELETE FROM inbound_order WHERE inbound_no IN ('CG-RK-20260401-0001', 'CG-RK-20260501-0001');

-- ------------------------------------------------------------
-- 四、核对：四项应全为 0（说明演示数据已清干净）
-- ------------------------------------------------------------
SELECT '演示订单残留' AS check_item,
       COUNT(*) AS violations
FROM purchase_order WHERE order_no LIKE 'CG-DD-2026%-0001' AND remark = '运营演示数据'
UNION ALL
SELECT '演示入库单残留', COUNT(*)
FROM inbound_order WHERE inbound_no IN ('CG-RK-20260401-0001', 'CG-RK-20260501-0001')
UNION ALL
-- 按明确批次号比对，不用 'B202604%' 通配：冒烟批次是「B + 当天日期 + 流水」，
-- 若某天正好在 4/5 月，通配会误报成残留
SELECT '演示批次库存残留', COUNT(*)
FROM stock_balance WHERE batch_no IN (
  'B20260401001', 'B20260401002', 'B20260401003', 'B20260401004', 'B20260401005',
  'B20260501001', 'B20260501002', 'B20260501003', 'B20260501004')
UNION ALL
SELECT '演示会签任务残留', COUNT(*)
FROM approval_task WHERE bill_no = 'CG-DD-20261027-0001';
